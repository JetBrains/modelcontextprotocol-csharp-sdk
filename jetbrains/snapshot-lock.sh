#!/usr/bin/env bash
# Refreshes jetbrains/lock/MainSolutionPackageVersions.subset.xml from the full main solution lock.
# usage: jetbrains/snapshot-lock.sh <path-to-MainSolutionPackageVersions.xml>
# The subset holds only the lock entries of packages this build resolves, copied verbatim, and every build of the fork uses it.
# Pinning acts only on packages in the restore graph, so a build against the subset resolves exactly what a build against the full lock does.
# Committed, it ties each fork revision to one set of versions, whatever the main solution has moved to since.
# Rerun it to take a lock move over, and after an upstream merge, since a new dependency is pinned only once it is in the subset.
set -euo pipefail
lock=$(realpath "$1")
fork=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$fork")
subset="$fork/lock/MainSolutionPackageVersions.subset.xml"

JB_PACKAGE_LOCK="$lock" "$fork/build.sh" restore -v quiet
assets="$root/artifacts/jetbrains/obj/ModelContextProtocol.Core/project.assets.json"

# The "libraries" keys of the assets file are "<id>/<version>"; the lock is looked up by id, case-insensitively as NuGet ids are.
mapfile -t ids < <(grep -oE '^    "[^"/]+/[^"/]+": \{' "$assets" | sed -E 's/^    "([^"/]+)\/.*/\1/' | sort -fu)
mkdir -p "$(dirname "$subset")"
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<!-- Generated by jetbrains/snapshot-lock.sh from the JetBrains main solution lock; the entries are verbatim, limited to the packages this build resolves. -->'
  echo '<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">'
  echo '  <ItemGroup>'
  for id in "${ids[@]}"; do
    grep -iE "^\s*<PackageLock Include=\"${id//./\\.}\" " "$lock" | tr -d '\r' | sed -E 's/^\s*/    /' || true
  done
  echo '  </ItemGroup>'
  echo '</Project>'
} > "$subset"
echo "Wrote $(grep -c '<PackageLock ' "$subset") entries of ${#ids[@]} resolved packages to $subset"
